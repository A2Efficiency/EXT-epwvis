#!/usr/bin/env python3
"""Convert us-atlas TopoJSON -> data/usGeo.js (a plain-GeoJSON JS global).

Emitted as a JS global rather than a .json fetched at runtime so the dashboard
works over file:// as well as http://, matching the data/stations.js convention.
"""
import json, sys
from pathlib import Path

SRC = Path("tools/states-10m.json")
OUT = Path("data/usGeo.js")
PRECISION = 2          # ~1 km; well under one pixel at locator-map scale

# FIPS ids d3.geo.albersUsa cannot project (it covers the 50 states + DC only).
SKIP_FIPS = {"60", "66", "69", "72", "78"}   # AS, GU, MP, PR, VI


def decode_arcs(topo):
    """Delta-decode + de-quantize every arc into absolute lon/lat coordinates."""
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    out = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append([round(x * sx + tx, PRECISION), round(y * sy + ty, PRECISION)])
        out.append(pts)
    return out


def ring(arc_indices, arcs):
    """Stitch a list of (possibly reversed) arc references into one ring."""
    pts = []
    for i in arc_indices:
        seg = arcs[i] if i >= 0 else arcs[~i][::-1]
        # Consecutive arcs share an endpoint; drop the duplicate.
        pts.extend(seg[1:] if pts else seg)
    return pts


def geometry(geom, arcs):
    t = geom["type"]
    if t == "Polygon":
        return {"type": "Polygon", "coordinates": [ring(r, arcs) for r in geom["arcs"]]}
    if t == "MultiPolygon":
        return {"type": "MultiPolygon",
                "coordinates": [[ring(r, arcs) for r in poly] for poly in geom["arcs"]]}
    raise ValueError("unexpected geometry type " + t)


def features(topo, arcs, layer, keep_props):
    out = []
    for g in topo["objects"][layer]["geometries"]:
        if g.get("id") in SKIP_FIPS:
            continue
        props = {k: g.get("properties", {}).get(k) for k in keep_props}
        props["id"] = g.get("id")
        out.append({"type": "Feature", "properties": props, "geometry": geometry(g, arcs)})
    return {"type": "FeatureCollection", "features": out}


def main():
    if not SRC.exists():
        sys.exit(f"missing {SRC}")
    topo = json.loads(SRC.read_text())
    arcs = decode_arcs(topo)
    states = features(topo, arcs, "states", ["name"])
    nation = features(topo, arcs, "nation", ["name"])

    OUT.parent.mkdir(exist_ok=True)
    payload = {"states": states, "nation": nation}
    js = ("// Generated by tools/topo2geo.py from us-atlas@3 states-10m.json\n"
          "// Source: https://github.com/topojson/us-atlas (Natural Earth 1:10m, public domain)\n"
          "var US_GEO = " + json.dumps(payload, separators=(",", ":")) + ";\n")
    OUT.write_text(js)
    print(f"wrote {OUT}  {OUT.stat().st_size/1024:.0f} KB  "
          f"states={len(states['features'])} nation={len(nation['features'])}")


if __name__ == "__main__":
    main()
